    private static android.graphics.Bitmap darkBitmap;
    private static android.graphics.Bitmap lightBitmap;

    public static Bitmap getBackground(boolean isDark) {
        if (isDark) {
            synchronized (CheckboxPrimitiveBackground.class) {
                if (darkBitmap == null)
                    darkBitmap = createBitmap(DARK_DATA);
                return darkBitmap;
            }
        } else {
            synchronized (CheckboxPrimitiveBackground.class) {
                if (lightBitmap == null)
                    lightBitmap = createBitmap(LIGHT_DATA);
                return lightBitmap;
            }
        }
    }

    /**
     * Clears the static bitmap cache to free memory.
     * Optional method for memory management in low-memory situations.
     */
    public static void clearCache() {
        synchronized (CheckboxPrimitiveBackground.class) {
            if (darkBitmap != null) {
                darkBitmap.recycle();
                darkBitmap = null;
            }
            if (lightBitmap != null) {
                lightBitmap.recycle();
                lightBitmap = null;
            }
        }
    }

    private static Bitmap createBitmap(char[] data) {
        int[] pixels = new int[WIDTH * HEIGHT];
        int offset = 0;

        for (int i = 0; i < data.length; i++) {
            int val = data[i];
            int colorIdx = (val >> 8) & 0xFF;
            int count = val & 0xFF;
            int color = PALETTE[colorIdx];
            for (int j = 0; j < count; j++) {
                if (offset < pixels.length) {
                    pixels[offset++] = color;
                }
            }
        }
        return Bitmap.createBitmap(pixels, WIDTH, HEIGHT, Bitmap.Config.ARGB_8888);
    }
